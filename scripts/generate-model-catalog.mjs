import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, '..');
const sourcePath = path.join(repositoryRoot, 'config', 'model-catalog.json');
const generatedFiles = new Map([
  [
    path.join(repositoryRoot, 'services', 'agent', 'ai', 'model_catalog_generated.py'),
    (models) => `# Generated by npm run models:generate; edit config/model-catalog.json instead.\nMODEL_CATALOG = ${toPythonLiteral(models)}\n`,
  ],
  [
    path.join(repositoryRoot, 'server', 'src', 'routes', 'model-catalog.generated.ts'),
    (models) => {
      const providers = [...new Set(models.map((model) => model.provider))];
      const entries = providers.map((provider) => {
        const ids = models
          .filter((model) => model.provider === provider)
          .map((model) => `    ${JSON.stringify(model.id)},`)
          .join('\n');
        return `  ${provider}: [\n${ids}\n  ],`;
      });
      return `// Generated by npm run models:generate; edit config/model-catalog.json instead.\nexport const PROVIDER_MODELS: Record<string, string[]> = {\n${entries.join('\n')}\n};\n`;
    },
  ],
]);

function toPythonLiteral(value) {
  if (value === null) return 'None';
  if (typeof value === 'boolean') return value ? 'True' : 'False';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(toPythonLiteral).join(', ')}]`;
  if (typeof value === 'object') {
    return `{${Object.entries(value)
      .map(([key, item]) => `${JSON.stringify(key)}: ${toPythonLiteral(item)}`)
      .join(', ')}}`;
  }
  throw new Error(`Unsupported catalog value type: ${typeof value}`);
}

const catalog = JSON.parse(await readFile(sourcePath, 'utf8'));
if (!catalog || !Array.isArray(catalog.models) || catalog.models.length === 0) {
  throw new Error('config/model-catalog.json must define a non-empty models array.');
}

const modelKeys = new Set();
for (const model of catalog.models) {
  if (
    !model ||
    typeof model.id !== 'string' ||
    typeof model.provider !== 'string' ||
    typeof model.display_name !== 'string' ||
    !model.capabilities ||
    typeof model.capabilities !== 'object'
  ) {
    throw new Error('Every model must include id, provider, display_name, and capabilities.');
  }
  const modelKey = `${model.provider}:${model.id}`;
  if (modelKeys.has(modelKey)) throw new Error(`Duplicate model in catalog: ${modelKey}`);
  modelKeys.add(modelKey);
}

const checkOnly = process.argv.includes('--check');
const failures = [];
for (const [outputPath, render] of generatedFiles) {
  const expected = render(catalog.models);
  if (checkOnly) {
    let actual = '';
    try {
      actual = await readFile(outputPath, 'utf8');
    } catch {}
    if (actual !== expected) failures.push(path.relative(repositoryRoot, outputPath));
    continue;
  }
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected, 'utf8');
}

if (failures.length > 0) {
  console.error(`Generated model catalogs are stale: ${failures.join(', ')}. Run npm run models:generate.`);
  process.exitCode = 1;
} else if (checkOnly) {
  console.log('Generated model catalogs match config/model-catalog.json.');
} else {
  console.log('Generated model catalogs from config/model-catalog.json.');
}
