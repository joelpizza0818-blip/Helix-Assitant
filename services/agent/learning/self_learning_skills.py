"""Self-Learning Skill Layer for HELIX Adaptive Harness.

Inspired by AutoHarness:
- Scenario Fusion: Identifies recurring tool sequences across episodic memory and
  synthesizes them into dynamic self-authored skills.
- Active Pruning: Monitors usage, success, and rejection; automatically prunes
  or deactivates skills the user no longer uses or accepts.
"""

from __future__ import annotations

import json
import logging
import re
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

DEFAULT_LEARNED_SKILLS_DIR = Path.home() / ".helix" / "learned_skills"


class SelfLearningSkillManager:
    """Manages the lifecycle of automatically created and pruned skills."""

    def __init__(
        self,
        skills_dir: Optional[Path] = None,
        episodic_memory=None,
        skill_registry=None,
    ):
        self.skills_dir = Path(skills_dir or DEFAULT_LEARNED_SKILLS_DIR)
        self.skills_dir.mkdir(parents=True, exist_ok=True)
        self.episodic_memory = episodic_memory
        self.skill_registry = skill_registry
        self.metrics_file = self.skills_dir / "skills_telemetry.json"
        self._ensure_metrics()

    def _ensure_metrics(self) -> None:
        if not self.metrics_file.exists():
            self.metrics_file.write_text("{}", encoding="utf-8")

    def load_telemetry(self) -> Dict[str, Dict[str, Any]]:
        try:
            content = self.metrics_file.read_text(encoding="utf-8").strip()
            return json.loads(content) if content else {}
        except Exception:
            return {}

    def save_telemetry(self, data: Dict[str, Dict[str, Any]]) -> None:
        temp = self.metrics_file.with_suffix(".tmp")
        temp.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
        temp.replace(self.metrics_file)

    def record_skill_usage(self, skill_name: str, succeeded: bool = True) -> None:
        """Records telemetry when a learned skill is triggered."""
        telemetry = self.load_telemetry()
        entry = telemetry.setdefault(
            skill_name,
            {
                "invocations": 0,
                "successes": 0,
                "rejections": 0,
                "last_used": None,
                "created_at": datetime.now(timezone.utc).isoformat(),
            },
        )
        entry["invocations"] += 1
        if succeeded:
            entry["successes"] += 1
        else:
            entry["rejections"] += 1
        entry["last_used"] = datetime.now(timezone.utc).isoformat()
        self.save_telemetry(telemetry)

    def synthesize_skill_from_pattern(
        self,
        name: str,
        description: str,
        tool_sequence: List[str],
        sample_queries: List[str],
    ) -> Optional[Path]:
        """Synthesizes a new self-learned skill with frontmatter and instructions."""
        clean_name = re.sub(r"[^a-z0-9_-]", "-", name.lower().strip()).strip("-")
        if not clean_name:
            clean_name = f"learned-skill-{uuid.uuid4().hex[:6]}"

        skill_folder = self.skills_dir / clean_name
        skill_folder.mkdir(parents=True, exist_ok=True)
        skill_file = skill_folder / "SKILL.md"

        triggers_yaml = "\n".join([f"  - \"{q.strip()}\"" for q in sample_queries[:4]])
        tools_yaml = "\n".join([f"  - \"{t.strip()}\"" for t in tool_sequence])

        content = f"""---
name: {clean_name}
description: "{description}"
version: "1.0.0"
triggers:
{triggers_yaml}
tools:
{tools_yaml}
---

# Learned Skill: {clean_name}

> Auto-generated by HELIX Self-Learning Skill Layer based on repeated user patterns.

## Instructions
1. When the user requests an operation matching these patterns ({', '.join(sample_queries[:2])}):
2. Execute the verified tool sequence in order:
{chr(10).join([f"   - Step {idx+1}: `{tool}`" for idx, tool in enumerate(tool_sequence)])}
3. Confirm the outcome concisely.
"""
        skill_file.write_text(content, encoding="utf-8")
        logger.info("Synthesized self-learned skill at: %s", skill_file)

        # Update telemetry
        telemetry = self.load_telemetry()
        telemetry[clean_name] = {
            "invocations": 1,
            "successes": 1,
            "rejections": 0,
            "last_used": datetime.now(timezone.utc).isoformat(),
            "created_at": datetime.now(timezone.utc).isoformat(),
        }
        self.save_telemetry(telemetry)

        # Register in dynamic skill registry if provided
        if self.skill_registry is not None:
            try:
                from services.agent.skills.skill_loader import SkillLoader
                loader = SkillLoader()
                skill_def = loader.load_from_file(str(skill_file))
                self.skill_registry.register_skill(skill_def)
            except Exception as e:
                logger.warning("Could not automatically register dynamic skill: %s", e)

        return skill_file

    def run_auto_fusion(self, min_frequency: int = 3) -> List[str]:
        """Scans episodic memory for recurring tool action chains and creates skills."""
        if self.episodic_memory is None:
            return []

        patterns = self.episodic_memory.find_frequent_tool_sequences(
            min_frequency=min_frequency, min_length=2
        )
        created = []
        telemetry = self.load_telemetry()

        for pat in patterns:
            seq = pat["sequence"]
            queries = pat.get("queries", [])
            base_name = f"macro-{'-'.join(seq[:3])}"
            if base_name in telemetry:
                continue  # Already synthesized

            first_query = queries[0] if queries else "automated action sequence"
            desc = f"Automated macro for recurring workflow: {first_query[:50]}"
            path = self.synthesize_skill_from_pattern(
                name=base_name,
                description=desc,
                tool_sequence=seq,
                sample_queries=queries,
            )
            if path:
                created.append(base_name)

        return created

    def prune_underperforming_skills(
        self, min_invocations: int = 5, max_rejection_ratio: float = 0.5
    ) -> List[str]:
        """Active pruning: deletes or disables skills that fail user validation."""
        telemetry = self.load_telemetry()
        pruned = []

        for skill_name, stats in list(telemetry.items()):
            invocations = stats.get("invocations", 0)
            rejections = stats.get("rejections", 0)

            if invocations >= min_invocations:
                rejection_ratio = rejections / max(1, invocations)
                if rejection_ratio > max_rejection_ratio:
                    # Prune skill folder
                    skill_folder = self.skills_dir / skill_name
                    if skill_folder.exists():
                        import shutil
                        shutil.rmtree(skill_folder, ignore_errors=True)
                    del telemetry[skill_name]
                    pruned.append(skill_name)
                    logger.info("Pruned underperforming skill: %s (rejection ratio: %.2f)", skill_name, rejection_ratio)
                    if self.skill_registry is not None:
                        self.skill_registry.unregister_skill(skill_name)

        if pruned:
            self.save_telemetry(telemetry)
        return pruned
